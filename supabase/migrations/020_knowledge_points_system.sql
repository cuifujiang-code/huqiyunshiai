/**
 * 020 · 知识点层级树 knowledge_points
 * 四级结构：grade → chapter → knowledge_point → exam_point
 * 示例数据：高中数学 · 高三（完整章节）
 */

CREATE TABLE IF NOT EXISTS public.knowledge_points (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name TEXT NOT NULL,
  parent_id UUID REFERENCES public.knowledge_points(id) ON DELETE CASCADE,
  level TEXT NOT NULL CHECK (level IN ('grade', 'chapter', 'knowledge_point', 'exam_point')),
  subject TEXT NOT NULL DEFAULT '数学',
  grade TEXT,
  sort_order INT NOT NULL DEFAULT 0,
  code TEXT UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS kp_parent_id_idx ON public.knowledge_points (parent_id);
CREATE INDEX IF NOT EXISTS kp_subject_grade_idx ON public.knowledge_points (subject, grade);
CREATE INDEX IF NOT EXISTS kp_level_idx ON public.knowledge_points (level);
CREATE INDEX IF NOT EXISTS kp_code_idx ON public.knowledge_points (code);

ALTER TABLE public.knowledge_points ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "deny_direct_kp" ON public.knowledge_points;
CREATE POLICY "deny_direct_kp" ON public.knowledge_points FOR ALL USING (false) WITH CHECK (false);

COMMENT ON TABLE public.knowledge_points IS '学科知识点四级树：年级→章节→知识点→考点';
COMMENT ON COLUMN public.knowledge_points.level IS 'grade | chapter | knowledge_point | exam_point';
COMMENT ON COLUMN public.knowledge_points.code IS '与 knowledge-base/subject-knowledge-tree.json 节点 id 对应';

